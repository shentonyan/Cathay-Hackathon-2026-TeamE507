import { readFileSync, writeFileSync } from 'node:fs';
import { isAbsolute, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import MathJax from 'mathjax';

const output = new URL('../../site/assets/data/model-formulas.js', import.meta.url);
let ready;

function init() {
  ready ??= MathJax.init({
    loader: {
      // tex-base excludes the extensions that silently display invalid TeX.
      load: [
        'input/tex-base',
        '[tex]/ams',
        '[tex]/newcommand',
        '[tex]/configmacros',
        'output/svg',
      ],
      // Node's ESM loader requires file URLs for absolute Windows paths.
      require: (path) => import(isAbsolute(path) ? pathToFileURL(path).href : path),
    },
    tex: {
      packages: ['base', 'ams', 'newcommand', 'configmacros'],
      macros: { argmin: '\\mathop{\\mathrm{arg\\,min}}\\limits' },
      formatError: (_jax, error) => {
        throw new Error(error.message, { cause: error });
      },
    },
    // Each SVG includes its glyph paths. No font files, shared IDs or CDN.
    svg: { fontCache: 'none' },
  });
  return ready;
}

/** Split presentation clauses without changing any mathematical tokens. */
export function splitClauses(tex) {
  const parts = [];
  let braces = 0;
  let start = 0;
  for (let i = 0; i < tex.length; i += 1) {
    if (tex[i] === '\\') {
      if (braces === 0 && /^\\qquad(?![a-zA-Z])/.test(tex.slice(i))) {
        parts.push(tex.slice(start, i).trim());
        i += '\\qquad'.length - 1;
        start = i + 1;
      } else {
        // An escaped brace is a delimiter, not a TeX grouping brace.
        const command = /^\\(?:[a-zA-Z]+|.)/.exec(tex.slice(i));
        if (command) i += command[0].length - 1;
      }
    } else if (tex[i] === '{') braces += 1;
    else if (tex[i] === '}') braces -= 1;
  }
  parts.push(tex.slice(start).trim());
  return parts.flatMap(splitLongSum);
}

function splitLongSum(tex) {
  if (tex.length <= 180) return [tex];
  const cuts = [];
  let depth = 0;
  for (let i = 0; i < tex.length; i += 1) {
    const char = tex[i];
    if (char === '\\') {
      const command = /^\\(?:[a-zA-Z]+|.)/.exec(tex.slice(i));
      if (command) i += command[0].length - 1;
    } else if ('{(['.includes(char)) depth += 1;
    else if ('})]'.includes(char)) depth -= 1;
    else if (depth === 0 && (char === '+' || char === '-')) cuts.push(i);
  }
  if (cuts.length < 3) return [tex];
  // Continue long sums after every two terms, keeping each leading operator.
  const rows = [];
  let start = 0;
  for (let k = 1; k < cuts.length; k += 2) {
    rows.push(tex.slice(start, cuts[k]).trim());
    start = cuts[k];
  }
  rows.push(tex.slice(start).trim());
  return rows;
}

async function typeset(tex, label, display) {
  await init();
  const node = await MathJax.tex2svgPromise(tex, { display });
  const adaptor = MathJax.startup.adaptor;
  const svg = adaptor.firstChild(node);
  if (adaptor.kind(svg) !== 'svg') {
    throw new Error(`Expected an SVG for ${label}`);
  }
  adaptor.setAttribute(svg, 'aria-label', `${label}: ${tex}`);
  const rendered = adaptor.serializeXML(svg);
  if (/data-mml-node="merror"|data-mjx-error=/.test(rendered)) {
    throw new Error(`Invalid TeX in ${label}: ${tex}`);
  }
  return rendered;
}

/** Render the original specification; all source TeX remains inspectable. */
export async function typesetModel(spec) {
  const secs = [];
  for (const section of spec.secs) {
    const eqs = [];
    for (const equation of section.eqs) {
      const { n, h, tex, p } = equation;
      const clauses = splitClauses(tex);
      const mml = await typeset(tex, h, true);
      const parts = [];
      for (const clause of clauses) {
        parts.push(clauses.length === 1 ? mml : await typeset(clause, h, true));
      }
      eqs.push({ n, h, tex, mml, parts, p });
    }
    secs.push({ c: section.c, t: section.t, eqs });
  }
  const syms = [];
  for (const row of spec.syms) {
    const { g, tex, n, path, v, u, src } = row;
    syms.push({ g, tex, s: await typeset(tex, n, false), n, path, v, u, src });
  }
  return { secs, syms };
}

export function serializeModel(model) {
  return (
    '/* Offline MathJax 4.1.3 / MathJax New Computer Modern 4.1.3 SVG formulas.\n' +
    ' * Generated by scripts/site/build_formulas.py from model_spec.py.\n' +
    ' * Original TeX is retained; no browser math library or external fonts. */\n' +
    `const MODEL9=${JSON.stringify(model)};\n`
  );
}

async function main() {
  const model = await typesetModel(JSON.parse(readFileSync(0, 'utf8')));
  const generated = serializeModel(model);
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== generated) {
      throw new Error('Formula output is stale; run scripts/site/build_formulas.py');
    }
    console.log('Offline formula output matches the source specification.');
  } else {
    writeFileSync(output, generated);
    console.log(
      `${model.secs.flatMap((section) => section.eqs).length} formulas, ` +
        `${model.syms.length} symbols -> ${fileURLToPath(output)}`,
    );
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
